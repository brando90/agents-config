#!/usr/bin/env python3
"""Build the mega tech report: every per-result .tex in <latex-dir>/results/, in chronological order, as one PDF.

Use when a research repo follows Rule 93 (one .tex per result) and you add or change a result, or want the whole
record of results as one document. Needs python3 only; compiling needs latexmk or pdflatex on PATH.

  python3 build_mega_report.py --latex-dir latex --init     # first time: create the folder, preamble, template
  python3 build_mega_report.py --latex-dir latex            # regenerate mega_meta.tex, mega_results.tex, the PDF
  python3 build_mega_report.py --latex-dir latex --single 25   # standalone PDF of result 25 only
  python3 build_mega_report.py --latex-dir latex --check    # headers and order only, no compile

Each results/NN_<slug>.tex starts with header lines (see templates/result_template.tex):
  %% title:, %% result-date: MM-DD-YYYY, %% result-time: HH:MM (optional), %% experiment:, %% headline:
Order: result-date, then result-time, then NN. result-date = the day the result first landed on main.
"""
import argparse
import datetime as dt
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATES = HERE / "templates"
REQUIRED = ("title", "result-date", "experiment", "headline")
NAME = re.compile(r"^(\d+)([a-z]?)_[A-Za-z0-9_\-]+\.tex$")
HEADER = re.compile(r"^%%\s*([a-z\-]+):\s*(.*?)\s*$")


def parse(path):
    meta = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = HEADER.match(line)
        if m:
            meta[m[1]] = m[2]
        elif line.strip() and not line.startswith("%"):
            break
    return meta


def load(results_dir):
    rows, errors = [], []
    for path in sorted(results_dir.glob("*.tex")):
        if path.name.startswith("_"):
            continue
        name = NAME.match(path.name)
        if not name:
            errors.append(f"{path.name}: file name must be NN_<slug>.tex (NN = experiment number)")
            continue
        meta = parse(path)
        missing = [k for k in REQUIRED if not meta.get(k)]
        if missing:
            errors.append(f"{path.name}: missing header lines {', '.join('%% ' + k + ':' for k in missing)}")
            continue
        try:
            when = dt.datetime.strptime(meta["result-date"] + " " + meta.get("result-time", "00:00"), "%m-%d-%Y %H:%M")
        except ValueError:
            errors.append(f"{path.name}: result-date must be MM-DD-YYYY and result-time HH:MM")
            continue
        body = path.read_text(encoding="utf-8")
        if "\\documentclass" in body or "\\begin{document}" in body:
            errors.append(f"{path.name}: a result file is a fragment, no \\documentclass or \\begin{{document}}")
        rows.append({"path": path, "num": int(name[1]), "suffix": name[2], "when": when, "meta": meta})
    rows.sort(key=lambda r: (r["when"], r["num"], r["suffix"]))
    return rows, errors


def write_generated(latex_dir, rows, built):
    meta = ["% Generated by build_mega_report.py; do not edit.",
            f"\\newcommand{{\\MegaBuilt}}{{{built}}}",
            f"\\newcommand{{\\MegaCount}}{{{len(rows)}}}"]
    (latex_dir / "mega_meta.tex").write_text("\n".join(meta) + "\n", encoding="utf-8")
    out = ["% Generated by build_mega_report.py; do not edit. Chronological: result-date, result-time, NN.",
           "\\section*{Results at a glance}",
           "\\begin{longtable}{@{}r l r p{0.60\\textwidth}@{}}",
           "\\toprule No. & Result date & Exp. & Headline \\\\ \\midrule \\endhead"]
    for i, r in enumerate(rows, 1):
        m = r["meta"]
        out.append(f"{i} & {m['result-date']} & {r['num']}{r['suffix']} & {m['headline']} \\\\")
    out += ["\\bottomrule", "\\end{longtable}", ""]
    for i, r in enumerate(rows, 1):
        m = r["meta"]
        stamp = m["result-date"] + (" " + m["result-time"] if m.get("result-time") else "")
        out += ["\\clearpage",
                f"\\section{{{m['title']}}}",
                f"\\ResultMeta{{{i}}}{{{r['num']}{r['suffix']}}}{{{stamp}}}{{{m['experiment']}}}",
                f"\\input{{results/{r['path'].stem}}}", ""]
    (latex_dir / "mega_results.tex").write_text("\n".join(out), encoding="utf-8")


def compile_pdf(latex_dir, tex):
    if shutil.which("latexmk"):
        cmd = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", tex]
        run = subprocess.run(cmd, cwd=latex_dir, capture_output=True, text=True)
    elif shutil.which("pdflatex"):
        run = None
        for _ in range(2):
            run = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex],
                                 cwd=latex_dir, capture_output=True, text=True)
    else:
        sys.exit("No latexmk or pdflatex on PATH: the .tex files are written, the PDF is not built.")
    if run.returncode != 0:
        print(run.stdout[-3000:])
        sys.exit(f"LaTeX failed on {tex}")
    stem = Path(tex).stem
    for ext in ("aux", "log", "out", "toc", "fls", "fdb_latexmk", "lof", "lot"):
        (latex_dir / f"{stem}.{ext}").unlink(missing_ok=True)
    print(f"built {latex_dir / (stem + '.pdf')}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--latex-dir", default="latex", help="the repo's LaTeX folder (default: latex)")
    ap.add_argument("--init", action="store_true", help="create results/, mega_preamble.tex, mega_tech_report.tex, a template")
    ap.add_argument("--single", metavar="NN", help="build a standalone PDF of one result (its experiment number, e.g. 25 or 25b)")
    ap.add_argument("--check", action="store_true", help="check headers and order, no compile")
    ap.add_argument("--no-compile", action="store_true", help="write the generated .tex files only")
    ap.add_argument("--date", help="build date MM-DD-YYYY (default: today)")
    args = ap.parse_args()
    latex_dir = Path(args.latex_dir)
    results = latex_dir / "results"
    if args.init:
        results.mkdir(parents=True, exist_ok=True)
        for src, dst in (("mega_preamble.tex", latex_dir / "mega_preamble.tex"),
                         ("mega_tech_report.tex", latex_dir / "mega_tech_report.tex"),
                         ("result_template.tex", results / "_TEMPLATE.tex")):
            if not dst.exists():
                shutil.copy(TEMPLATES / src, dst)
                print(f"created {dst}")
        return
    if not results.is_dir():
        sys.exit(f"{results} not found; run with --init first")
    rows, errors = load(results)
    for e in errors:
        print("ERROR:", e)
    if errors:
        sys.exit(1)
    if not rows:
        sys.exit("No result files yet.")
    built = args.date or dt.date.today().strftime("%m-%d-%Y")
    if args.check:
        for i, r in enumerate(rows, 1):
            print(i, r["meta"]["result-date"], r["meta"].get("result-time", ""), r["path"].name)
        return
    write_generated(latex_dir, rows, built)
    if args.single:
        want = re.fullmatch(r"(\d+)([a-z]?)", args.single)
        pick = [r for r in rows if want and (r["num"], r["suffix"]) == (int(want[1]), want[2])]
        if not pick:
            sys.exit(f"no result file for {args.single}")
        r = pick[0]
        wrapper = latex_dir / f"single_{r['path'].stem}.tex"
        m = r["meta"]
        wrapper.write_text(
            "\\documentclass[11pt]{article}\n\\input{mega_preamble}\n\\input{mega_meta}\n"
            f"\\title{{{m['title']}}}\n\\author{{Brando Miranda}}\n\\date{{Result of {m['result-date']}}}\n"
            "\\begin{document}\n\\maketitle\n"
            f"\\input{{results/{r['path'].stem}}}\n\\end{{document}}\n", encoding="utf-8")
        if not args.no_compile:
            compile_pdf(latex_dir, wrapper.name)
        return
    if not args.no_compile:
        compile_pdf(latex_dir, "mega_tech_report.tex")


if __name__ == "__main__":
    main()
